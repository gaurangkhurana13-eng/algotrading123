def build_strategy_version_files(v_dir: Path, version_tag: str, hypothesis: dict):
    v_dir.mkdir(parents=True, exist_ok=True)
    
    # 1. config.json
    (v_dir / "config.json").write_text(json.dumps(hypothesis["params"], indent=2), encoding="utf-8")
    
    # 2. vX.pine & strategy.pine
    pine_code = generate_pine_script(version_tag, hypothesis)
    (v_dir / f"{version_tag.lower()}.pine").write_text(pine_code, encoding="utf-8")
    (v_dir / "strategy.pine").write_text(pine_code, encoding="utf-8")
    
    # 3. run_vX.py & strategy.py
    py_code = generate_python_runner(version_tag, hypothesis)
    (v_dir / f"run_{version_tag.lower()}.py").write_text(py_code, encoding="utf-8")
    (v_dir / "strategy.py").write_text(py_code, encoding="utf-8")
